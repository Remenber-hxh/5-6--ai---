// ===== 语义色 =====
//
// 【为什么要有这个文件】同一屏上的两个组件曾经各用一套近似色:
// 绿 #12a968 / #3f9e79、橙 #f5a524 / #d4713a、次要文字 #8aa0b0 / #8a99a5、
// 分隔线 #f0f2f5 / #f0f0f0。每一对肉眼几乎分不出,合在一起就是"说不上来
// 哪里脏"—— 而且没人会去比对两个组件的色值。
//
// 【按角色命名,不按颜色命名】写 GREEN 的话,哪天"完成"要换成蓝色,
// 就会出现一个叫 GREEN 的蓝色常量,然后没人敢改。
//
// 取值沿用计划页的那一套 —— 它和 antd Tag 的绿/蓝/红是配套的,
// 换成另一套会让标签和正文对不上。
export const C = {
  /** 完成 / 正常 */
  ok: "#12a968",
  /** 待办 / 需要注意,但还不是故障 */
  warn: "#f5a524",
  /** 异常 / 逾期 */
  danger: "#ef4b3f",
  /** 进行中 */
  progress: "#246bfe",

  /** 正文 */
  text: "#1c2b3a",
  /** 次要文字(说明、时间戳) */
  textSub: "#5b6b78",
  /** 更弱的文字(字段名、占位) */
  textFaint: "#8aa0b0",

  /** 分隔线 */
  line: "#f0f2f5",
  /** 未激活的圆点、禁用态 */
  muted: "#d9dee4",
} as const;
